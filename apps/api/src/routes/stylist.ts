import { Router } from "express";
import { seedProducts } from "@cheshire/database/catalog";

export const stylistRouter = Router();

stylistRouter.post("/", (req, res) => {
  const { occasion = "EVERYDAY", style = "MINIMAL", budget = "999_1999" } = req.body || {};
  const ranges: Record<string, [number, number]> = {
    UNDER_999: [0, 999],
    "999_1999": [999, 1999],
    "1999_4999": [1999, 4999],
    "5000_PLUS": [5000, 100000],
  };
  const [min, max] = ranges[budget] || [0, 100000];
  const products = seedProducts
    .filter((p) => p.price >= min && p.price <= max)
    .filter(
      (p) =>
        p.moods.some((m) => m.includes(String(style).toUpperCase()) || String(style).toUpperCase().includes(m)) ||
        p.occasions.includes(String(occasion).toUpperCase())
    )
    .slice(0, 6);

  res.json({
    lookName: `${style} ${occasion} Edit`.toUpperCase(),
    rationale: "Generated by CHESHIRE Stylist rules engine. Replace with AI provider later.",
    products,
    completeLookIds: products.map((p) => p.sku),
  });
});
